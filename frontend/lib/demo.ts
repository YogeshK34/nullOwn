/**
 * Demo mode — a fully populated NullOwn with no chain behind it.
 *
 * ---------------------------------------------------------------------------
 * Why this exists
 * ---------------------------------------------------------------------------
 * A fresh clone has no deployment and no circuit artifacts, so every panel
 * renders its "not configured" state and nothing can be clicked. That is honest
 * but useless for showing the system. With `NEXT_PUBLIC_DEMO_MODE=true` the
 * hooks swap their chain calls for the fixtures below and the whole app becomes
 * clickable end to end.
 *
 * ---------------------------------------------------------------------------
 * What is real and what is not
 * ---------------------------------------------------------------------------
 * Everything cryptographic stays real. Stealth keys are generated by the actual
 * secp256k1 code, announcements are derived with the real ECDH, the Merkle tree
 * is a real Poseidon tree, and the nullifier is the real Poseidon hash — so
 * "Reveal Controlling Key" genuinely re-derives a key that controls the address
 * it claims to.
 *
 * What is fabricated is everything that would otherwise need a chain: contract
 * addresses, block numbers, transaction hashes, the audit log, role
 * assignments, and the Groth16 proof bytes. Those are marked as such wherever
 * they surface.
 *
 * Demo mode is off unless explicitly switched on, and nothing here is imported
 * on a path that runs when it is off.
 */

