/**
 * Structurally identical to `AuditRecord` in `hooks/useCompliance`. Declared
 * here rather than imported so this module stays free of hook dependencies —
 * the hooks import demo data, never the other way round.
 */
export interface DemoAudit {
  id: number;
  regulator: Address;
  scope: string;
  scopeLabel: string;
  timestamp: number;
  fulfilled: boolean;
  encryptedResponse: string;
}

/** Ciphertext blob — deterministic, meaningless, and obviously not plaintext. */
function demoCiphertext(seed: string, words: number): string {
  let out = "0x";
  for (let i = 0; i < words; i++) {
    out += keccak256(toUtf8Bytes(`nullown-demo-cipher/${seed}/${i}`)).slice(2);
  }
  return out;
}

function auditScope(label: string): { scope: string; scopeLabel: string } {
  return { scope: encodeBytes32String(label), scopeLabel: label };
}

