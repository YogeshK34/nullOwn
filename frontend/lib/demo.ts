/**
 * A 32-byte scalar from a label.
 *
 * keccak of a fixed string gives a stable, valid secp256k1 private key — the
 * chance of landing outside the scalar field is ~2^-128, and `importStealthKeys`
 * would reject it loudly rather than silently misbehave.
 */
function scalarFromSeed(seed: string): Hex {
  return keccak256(toUtf8Bytes(`nullown-demo/${seed}`)) as Hex;
}

/**
 * The stealth keys the demo pretends a given account owns.
 *
 * Derived from the address so every account in the demo has a stable, distinct
 * meta-address — two lookups of the same address always agree, and two
 * different addresses never collide.
 */
export function demoKeysFor(account: string): StealthKeys {
  const lower = account.toLowerCase();
  return importStealthKeys(scalarFromSeed(`spend/${lower}`), scalarFromSeed(`view/${lower}`));
}

/** Registry entry the demo returns for an account with no explicit registration. */
export function demoMetaAddressFor(account: string): StealthMetaAddress {
  return metaAddressFromKeys(demoKeysFor(account));
}

