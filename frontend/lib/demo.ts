/**
 * Groth16 proof points.
 *
 * These are fabricated field elements. They have the right shape for
 * `verifyOwnership` — eight BN254 elements, `[a, b, c]` flattened — and a real
 * verifier would reject them, which is the correct outcome: demo mode never
 * submits them anywhere. The public signals shown next to them are computed for
 * real from the user's own input.
 *
 * Derived from a seed rather than typed out so every element is guaranteed to
 * be inside the scalar field. Truncating to 253 bits is enough: 2^253 - 1 is
 * below the BN254 modulus, so no reduction is needed and this module stays free
 * of the circomlibjs import that `lib/poseidon` carries — `lib/env` reaches
 * this file from the server-rendered layout.
 */
export const DEMO_PROOF_POINTS: readonly bigint[] = Array.from(
  { length: 8 },
  (_unused, index) =>
    BigInt(keccak256(toUtf8Bytes(`nullown-demo-proof/${index}`))) & ((1n << 253n) - 1n),
);

